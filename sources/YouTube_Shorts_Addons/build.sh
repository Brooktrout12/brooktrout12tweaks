#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")"
: "${THEOS:?Set THEOS to your Theos directory}"
: "${IOS_SDK_PATH:?Set IOS_SDK_PATH to an iPhoneOS SDK}"
IOS_TOOLCHAIN_BIN="${IOS_TOOLCHAIN_BIN:-$THEOS/toolchain/linux/iphone/bin}"
BUILD_ARCH="${BUILD_ARCH:-arm64}"
if [[ "$BUILD_ARCH" != arm64 ]]; then
    printf '%s\n' 'This package targets the arm64 App Store YouTube process.' >&2
    exit 1
fi
mkdir -p build dist
gcc -std=c11 -Wall -Wextra -Werror tests/foreground_state_test.c -o build/foreground_state_test
./build/foreground_state_test

components=("$@")
if [ ${#components[@]} -eq 0 ]; then components=(ForegroundOnly NoAds); fi
for component in "${components[@]}"; do
    name="YTShorts${component}"
    case "$component" in
        ForegroundOnly)
            version="1.0.1"
            package="local.kilian.ytshortsforegroundonly"
            title="YT Shorts Foreground Only"
            description="Pauses the Shorts player when YouTube loses focus. Rootless test build."
            ;;
        NoAds)
            version="1.0.0"
            package="local.kilian.ytshortsnoads"
            title="YT Shorts No Ads"
            description="Filters known video and non-video Shorts ad models. Rootless test build."
            ;;
        *) printf 'Unknown component: %s\n' "$component" >&2; exit 1 ;;
    esac
    stage="build/$name"
    # This directory is entirely generated by this build script.
    rm -rf -- "$stage"
    dylib_directory="$stage/var/jb/Library/MobileSubstrate/DynamicLibraries"
    docs_directory="$stage/var/jb/usr/share/doc/$package"
    mkdir -p "$dylib_directory" "$stage/DEBIAN" "$docs_directory"
    "$IOS_TOOLCHAIN_BIN/clang" \
        -target arm64-apple-ios15.0 -isysroot "$IOS_SDK_PATH" \
        -B "$IOS_TOOLCHAIN_BIN" -dynamiclib -fobjc-arc -fblocks -O2 \
        -Wall -Wextra -Werror -Wno-unused-parameter \
        -I "$THEOS/vendor/include" \
        -F "$THEOS/vendor/lib/iphone/rootless" \
        -L "$THEOS/vendor/lib/iphone/rootless" \
        -framework Foundation -framework UIKit -framework CoreGraphics -lobjc -lsubstrate \
        -Wl,-rpath,/var/jb/Library/Frameworks -Wl,-rpath,/var/jb/usr/lib \
        -Wl,-rpath,@loader_path/.jbroot/Library/Frameworks \
        -Wl,-install_name,"/var/jb/Library/MobileSubstrate/DynamicLibraries/$name.dylib" \
        "$component/Tweak.m" -o "$dylib_directory/$name.dylib"
    "$IOS_TOOLCHAIN_BIN/ldid" -S "$dylib_directory/$name.dylib"
    cat > "$dylib_directory/$name.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict><key>Filter</key><dict><key>Bundles</key><array><string>com.google.ios.youtube</string></array></dict></dict></plist>
PLIST
    cat > "$stage/DEBIAN/control" <<CONTROL
Package: $package
Name: $title
Version: $version
Architecture: iphoneos-arm64
Description: $description
Maintainer: Local Build
Author: Local Build
Section: Tweaks
Priority: optional
Depends: firmware (>= 15.0), mobilesubstrate (>= 0.9.5000)
CONTROL
    cp README.txt "$docs_directory/README.txt"
    cp Licenses/*.txt "$docs_directory/"
    chmod 0755 "$dylib_directory/$name.dylib"
    chmod 0644 "$dylib_directory/$name.plist" "$stage/DEBIAN/control" "$docs_directory/"*.txt
    dpkg-deb --root-owner-group -Zxz -z9 --build "$stage" "dist/${name}_${version}_rootless.deb"
done
python3 tests/audit_packages.py
